def _trazo_a_path(pts):
    """Convierte la lista de puntos de un trazo en un QPainterPath suavizado."""
    P = [QPointF(p[0], p[1]) for p in pts]
    corners = [len(p) > 2 for p in pts]
    path = QPainterPath(P[0])
    run = [0]
    runs = []
    for i in range(1, len(P)):
        run.append(i)
        if corners[i] and i != len(P) - 1:
            runs.append(run)
            run = [i]
    runs.append(run)
    for r in runs:
        q = [P[i] for i in r]
        if len(q) == 2:
            path.lineTo(q[1])
            continue
        n = len(q)
        for i in range(n - 1):
            p0, p1, p2 = q[max(i - 1, 0)], q[i], q[i + 1]
            p3 = q[min(i + 2, n - 1)]
            c1 = p1 + (p2 - p0) / 6.0
            c2 = p2 - (p3 - p1) / 6.0
            path.cubicTo(c1, c2, p2)
    return path


_cache = {}


def trazos(letra):
    """Lista de QPainterPath (espacio unitario) de la letra."""
    if letra not in _cache:
        _cache[letra] = [_trazo_a_path(t) for t in GLIFOS[letra]]
    return _cache[letra]


def muestras(letra, n=70):
    """Cada trazo como lista de n QPointF (para animar el dibujado)."""
    return [[p.pointAtPercent(i / (n - 1)) for i in range(n)] for p in trazos(letra)]

